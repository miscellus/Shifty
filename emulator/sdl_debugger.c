static const char *text_vs_src =
    "#version 300 es\n"
    "layout(location = 0) in vec4 a_pos_uv;\n" // xy = pixel coords, zw = uv
    "uniform vec2 u_screen_size;\n"
    "out vec2 v_uv;\n"
    "void main() {\n"
    "    vec2 ndc = (a_pos_uv.xy / u_screen_size) * 2.0 - 1.0;\n"
    "    ndc.y = -ndc.y;\n" // top-left origin in pixels
    "    gl_Position = vec4(ndc, 0.0, 1.0);\n"
    "    v_uv = a_pos_uv.zw;\n"
    "}\n";

static const char *text_fs_src =
    "#version 300 es\n"
    "precision mediump float;\n"
    "in vec2 v_uv;\n"
    "uniform sampler2D u_font_tex;\n"
    "uniform vec4 u_color;\n"
    "out vec4 frag_color;\n"
    "void main() {\n"
    "    float alpha = texture(u_font_tex, v_uv).r;\n"
    "    if (alpha < 0.5) discard;\n"
    "    frag_color = vec4(u_color.rgb, u_color.a * alpha);\n"
    "}\n";

typedef struct {
    GLuint program;
    GLuint vao;
    GLuint vbo;
    GLuint font_tex;
    GLint u_screen_size;
    GLint u_font_tex;
    GLint u_color;
} MonoTextRenderer;

static bool init_mono_text(MonoTextRenderer *tr) {
    // 16 columns x 6 rows = 96 glyph cells (128x48 px atlas)
    const int cols = 16;
    const int rows = 6;
    const int atlas_w = cols * 8;
    const int atlas_h = rows * 8;
    uint8_t atlas[128 * 48] = {0};

    for (int i = 0; i < 95; i++) {
        int gx = (i % cols) * 8;
        int gy = (i / cols) * 8;
        for (int row = 0; row < 8; row++) {
            uint8_t bits = FONT_8X8[i][row];
            for (int col = 0; col < 8; col++) {
                if (bits & (0x80u >> col)) {
                    atlas[(gy + row) * atlas_w + (gx + col)] = 255;
                }
            }
        }
    }

    GLuint vs = compile_shader(GL_VERTEX_SHADER, text_vs_src);
    GLuint fs = compile_shader(GL_FRAGMENT_SHADER, text_fs_src);
    tr->program = gl.CreateProgram();
    gl.AttachShader(tr->program, vs);
    gl.AttachShader(tr->program, fs);
    gl.LinkProgram(tr->program);

    tr->u_screen_size = gl.GetUniformLocation(tr->program, "u_screen_size");
    tr->u_font_tex    = gl.GetUniformLocation(tr->program, "u_font_tex");
    tr->u_color       = gl.GetUniformLocation(tr->program, "u_color");

    gl.GenVertexArrays(1, &tr->vao);
    gl.GenBuffers(1, &tr->vbo);
    gl.BindVertexArray(tr->vao);
    gl.BindBuffer(GL_ARRAY_BUFFER, tr->vbo);
    gl.BufferData(GL_ARRAY_BUFFER, 0, NULL, GL_DYNAMIC_DRAW);

    gl.EnableVertexAttribArray(0);
    gl.VertexAttribPointer(0, 4, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);

    glGenTextures(1, &tr->font_tex);
    glBindTexture(GL_TEXTURE_2D, tr->font_tex);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, atlas_w, atlas_h, 0, GL_RED, GL_UNSIGNED_BYTE, atlas);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);

    return true;
}

static void draw_mono_text(
    MonoTextRenderer *tr,
    const char *text,
    float x,
    float y,
    float scale,
    int screen_w,
    int screen_h,
    float r, float g, float b, float a
) {
    if (!text || !*text) return;

    const int cols = 16;
    const int rows = 6;
    const float atlas_w = (float)(cols * 8);
    const float atlas_h = (float)(rows * 8);
    const float glyph_w = 8.0f * scale;
    const float glyph_h = 8.0f * scale;

    size_t len = strlen(text);
    // 6 vertices per character (2 triangles); dynamically allocate if needed for large source views
    float *verts = (float *)malloc(len * 6 * 4 * sizeof(float));
    if (!verts) return;

    size_t vcount = 0;
    float cx = x;
    float cy = y;

    for (size_t i = 0; i < len; i++) {
        unsigned char ch = (unsigned char)text[i];
        if (ch == '\n') {
            cx = x;
            cy += glyph_h;
            continue;
        }
        if (ch == '\t') {
            cx += glyph_w * 4.0f;
            continue;
        }
        if (ch < 0x20 || ch > 0x7E) {
            ch = '?';
        }

        int idx = (int)ch - 0x20;
        int gx = (idx % cols) * 8;
        int gy = (idx / cols) * 8;

        float u0 = (float)gx / atlas_w;
        float v0 = (float)gy / atlas_h;
        float u1 = (float)(gx + 8) / atlas_w;
        float v1 = (float)(gy + 8) / atlas_h;

        float x0 = cx;
        float y0 = cy;
        float x1 = cx + glyph_w;
        float y1 = cy + glyph_h;

        float quad[24] = {
            x0, y0, u0, v0,
            x1, y0, u1, v0,
            x0, y1, u0, v1,

            x0, y1, u0, v1,
            x1, y0, u1, v0,
            x1, y1, u1, v1
        };
        memcpy(&verts[vcount * 4], quad, sizeof(quad));
        vcount += 6;
        cx += glyph_w;
    }

    if (vcount > 0) {
        gl.UseProgram(tr->program);
        gl.Uniform2f(tr->u_screen_size, (float)screen_w, (float)screen_h);
        gl.Uniform1i(tr->u_font_tex, 1);
        gl.Uniform4f(tr->u_color, r, g, b, a);

        gl.ActiveTexture(GL_TEXTURE1);
        glBindTexture(GL_TEXTURE_2D, tr->font_tex);

        gl.BindVertexArray(tr->vao);
        gl.BindBuffer(GL_ARRAY_BUFFER, tr->vbo);
        gl.BufferData(GL_ARRAY_BUFFER, (GLsizeiptr)(vcount * 4 * sizeof(float)), verts, GL_DYNAMIC_DRAW);
        glDrawArrays(GL_TRIANGLES, 0, (GLsizei)vcount);
    }

    free(verts);
}
